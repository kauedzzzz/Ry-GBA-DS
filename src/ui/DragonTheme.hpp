inline void fillRect(SDL_Renderer* r, SDL_Rect rect, SDL_Color c) noexcept {
    SDL_SetRenderDrawBlendMode(r, c.a < 255 ? SDL_BLENDMODE_BLEND : SDL_BLENDMODE_NONE);
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    SDL_RenderFillRect(r, &rect);
}

inline void strokeRect(SDL_Renderer* r, SDL_Rect rect, SDL_Color c) noexcept {
    SDL_SetRenderDrawBlendMode(r, c.a < 255 ? SDL_BLENDMODE_BLEND : SDL_BLENDMODE_NONE);
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    SDL_RenderDrawRect(r, &rect);
}

inline void drawPanel(SDL_Renderer* r, SDL_Rect rect, SDL_Color bg, SDL_Color border) noexcept {
    // Sombra projetada discreta estilo janela nativa melonDS
    fillRect(r, SDL_Rect{rect.x + 4, rect.y + 4, rect.w, rect.h}, SDL_Color{0, 0, 0, 110});
    fillRect(r, rect, bg);
    strokeRect(r, rect, border);
}

inline void drawButton(SDL_Renderer* r, SDL_Rect rect, std::string_view label, bool hovered, bool activeAccent = false) noexcept {
    const SDL_Color bg = activeAccent
        ? DragonPalette::DRAGON_RED
        : (hovered ? DragonPalette::SURFACE_HOVER : DragonPalette::SURFACE_SCALES);
    const SDL_Color border = activeAccent
        ? DragonPalette::DRAGON_RED
        : (hovered ? DragonPalette::DRAGON_RED : DragonPalette::BORDER_SUBTLE);

    fillRect(r, rect, bg);
    strokeRect(r, rect, border);

    const int tw = DragonFont::measureWidth(label, 1);
    const int tx = rect.x + std::max(4, (rect.w - tw) / 2);
    const int ty = rect.y + (rect.h - 8) / 2;
    DragonFont::drawText(r, label, tx, ty, 1, DragonPalette::TEXT_PRIMARY);
}

inline void drawCheckbox(SDL_Renderer* r, SDL_Rect box, bool checked, std::string_view label, bool hovered) noexcept {
    fillRect(r, box, checked ? DragonPalette::EMERALD_DIM : DragonPalette::SURFACE_SUNKEN);
    strokeRect(r, box, hovered ? DragonPalette::EMERALD_SCALE : (checked ? DragonPalette::EMERALD_SCALE : DragonPalette::BORDER_SUBTLE));
    if (checked) {
        DragonFont::drawText(r, "\xE2\x9C\x93", box.x + (box.w - 8) / 2, box.y + (box.h - 8) / 2, 1, DragonPalette::TEXT_PRIMARY);
    }
    DragonFont::drawText(r, label, box.x + box.w + 10, box.y + (box.h - 8) / 2, 1, DragonPalette::TEXT_PRIMARY);
}

